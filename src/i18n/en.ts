/** Traduce el nombre dentro de un <b>…</b>. */
function tr2(html: string): string {
  return html.replace(/<b>(.+?)<\/b>/, (_, n: string) => `<b>${tr(n)}</b>`);
}

export const translateString = (raw: string): string | null => {
  const s = raw.trim();
  if (!s) return null;
  const hit = EN[s];
  if (hit !== undefined && hit !== s) return hit;
  for (const [re, fn] of PATTERNS) {
    const m = s.match(re);
    if (m) return fn(m);
  }
  // «Etiqueta: n, Etiqueta: n» (descripciones accesibles de los gráficos)
  if (/^[^:]+: \d+(, [^:]+: \d+)*$/.test(s)) {
    return s.split(', ').map((p) => { const [l, n] = p.split(': '); return `${tr(l)}: ${n}`; }).join(', ');
  }
  return null;
};
